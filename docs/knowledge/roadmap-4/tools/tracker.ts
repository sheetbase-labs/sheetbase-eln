/**
 * Roadmap 4 tracker: keeps CHECKLIST.md and the status block in NEXT.md in
 * step with the nod task files in ../.nod/tasks (the source of truth).
 *
 *   pnpm roadmap:sync    apply ticked boxes to nod, roll finished steps up to
 *                        their task, then regenerate CHECKLIST.md and NEXT.md
 *   pnpm roadmap:check   exit 1 if CHECKLIST.md or NEXT.md is out of date
 *
 * Ticking a box in CHECKLIST.md marks that item done in nod on the next sync;
 * unticking a box that was ticked at the last sync reopens it. A box that has
 * not changed since the last sync follows nod, so changes made with nod
 * (`pnpm roadmap update <id> --status …`) win. The ticked state at the last
 * sync is kept in ../.nod/checklist-state.json. See ../GUIDE.md.
 */
import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { format } from 'prettier'
import { parse as parseYaml } from 'yaml'

export const ROADMAP_DIR = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '..',
)
const TASKS_DIR = join(ROADMAP_DIR, '.nod', 'tasks')
const CHECKLIST = join(ROADMAP_DIR, 'CHECKLIST.md')
const NEXT = join(ROADMAP_DIR, 'NEXT.md')
const STATE = join(ROADMAP_DIR, '.nod', 'checklist-state.json')
const BLOCK_START = '<!-- tracker:start -->'
const BLOCK_END = '<!-- tracker:end -->'

export type Status = 'todo' | 'in-progress' | 'backlog' | 'done' | 'cancelled'

export interface Item {
  id: string
  type: 'epic' | 'task' | 'subtask' | 'bug'
  title: string
  status: Status
  priority: string
  parent?: string
  related: string[]
  tags: string[]
}

/** Roadmap ID such as `DSYS-02` or `DSYS-02.1`, taken from the first tag. */
export function roadmapId(item: Item): string {
  return item.tags[0] ?? item.id
}

export function loadItems(dir = TASKS_DIR): Item[] {
  return readdirSync(dir)
    .filter((file) => file.endsWith('.md'))
    .map((file) => {
      const text = readFileSync(join(dir, file), 'utf8')
      const match = /^---\n([\s\S]*?)\n---/.exec(text)
      if (!match) throw new Error(`No frontmatter in ${file}`)
      const fm = parseYaml(match[1]) as Record<string, unknown>
      return {
        id: String(fm.id),
        type: fm.type as Item['type'],
        title: String(fm.title),
        status: fm.status as Status,
        priority: String(fm.priority),
        parent: fm.parent ? String(fm.parent) : undefined,
        related: (fm.related as string[] | undefined) ?? [],
        tags: (fm.tags as string[] | undefined) ?? [],
      }
    })
}

const num = (id: string) => Number(id.split('-').pop())
const byRoadmapId = (a: Item, b: Item) =>
  roadmapId(a).localeCompare(roadmapId(b), 'en', { numeric: true })

function children(items: Item[], parent: string, type: Item['type']): Item[] {
  return items
    .filter((item) => item.parent === parent && item.type === type)
    .sort(byRoadmapId)
}

const counted = (items: Item[]) => items.filter((i) => i.status !== 'cancelled')
const done = (items: Item[]) => items.filter((i) => i.status === 'done')

function line(item: Item, indent: string): string {
  const box = item.status === 'done' ? '[x]' : '[ ]'
  const rid = roadmapId(item)
  const label = item.title.startsWith(rid)
    ? item.title.slice(rid.length).replace(/^\s*—\s*/, '')
    : item.title
  const text = item.status === 'cancelled' ? `~~${label}~~ (cancelled)` : label
  const state = item.status === 'in-progress' ? ' — **in progress**' : ''
  const id = item.type === 'task' ? `**${rid}**` : rid
  return `${indent}- ${box} ${id} ${text}${state} \`${item.id}\``
}

export async function renderChecklist(items: Item[]): Promise<string> {
  const epics = items
    .filter((i) => i.type === 'epic')
    .sort((a, b) => num(a.id) - num(b.id))
  const tasks = counted(items.filter((i) => i.type === 'task'))
  const steps = counted(items.filter((i) => i.type === 'subtask'))
  const out: string[] = [
    '# Roadmap 4 checklist',
    '',
    '<!-- Generated by `pnpm roadmap:sync` from .nod/tasks. Tick a box and run the sync, or change status with `pnpm roadmap update <id> --status …`. Do not edit anything else by hand. -->',
    '',
    `**Progress:** ${done(tasks).length} of ${tasks.length} tasks and ${done(steps).length} of ${steps.length} steps done.`,
    '',
    'Each task links to its specification in [`tasks/`](tasks/README.md); the code in backticks is its nod ID. A task is done when its exit criterion is met; its steps are the PRs that get it there.',
    '',
  ]
  for (const epic of epics) {
    const epicTasks = counted(children(items, epic.id, 'task'))
    const stream = roadmapId(epic)
    out.push(
      `## ${epic.title} (${done(epicTasks).length}/${epicTasks.length})`,
      '',
      `Specification: [tasks/${stream}.md](tasks/${stream}.md) · nod \`${epic.id}\``,
      '',
    )
    for (const task of children(items, epic.id, 'task')) {
      out.push(line(task, ''))
      for (const step of children(items, task.id, 'subtask')) {
        out.push(line(step, '  '))
      }
    }
    out.push('')
  }
  return format(out.join('\n'), { parser: 'markdown' })
}

/** Items whose related (waits-on) items are not all done. */
export function isBlocked(item: Item, items: Item[]): boolean {
  return item.related.some(
    (id) => items.find((other) => other.id === id)?.status !== 'done',
  )
}

const PRIORITY_ORDER = ['critical', 'high', 'medium', 'low']

export async function renderNextBlock(items: Item[]): Promise<string> {
  const tasks = counted(items.filter((i) => i.type === 'task'))
  const epics = items.filter((i) => i.type === 'epic')
  const waves = [
    ...new Set(tasks.map((t) => t.tags.find((x) => x.startsWith('wave-')))),
  ]
    .filter(Boolean)
    .sort() as string[]
  const inProgress = items
    .filter((i) => i.status === 'in-progress' && i.type !== 'epic')
    .sort(byRoadmapId)
  const ready = tasks
    .filter((t) => t.status === 'todo' && !isBlocked(t, items))
    .sort(
      (a, b) =>
        PRIORITY_ORDER.indexOf(a.priority) -
          PRIORITY_ORDER.indexOf(b.priority) || byRoadmapId(a, b),
    )
    .slice(0, 10)
  const blocked = tasks.filter(
    (t) => t.status !== 'done' && isBlocked(t, items),
  )
  const md: string[] = [
    BLOCK_START,
    '',
    `_Generated by \`pnpm roadmap:sync\` from the nod tracker._`,
    '',
    '| Wave | Done | Tasks |',
    '| ---- | ---: | ----: |',
    ...waves.map((wave) => {
      const inWave = tasks.filter((t) => t.tags.includes(wave))
      return `| ${wave.replace('wave-', '')} | ${done(inWave).length} | ${inWave.length} |`
    }),
    `| **All** | **${done(tasks).length}** | **${tasks.length}** |`,
    '',
    '**In progress**',
    '',
    ...(inProgress.length
      ? inProgress.map(
          (i) =>
            `- ${roadmapId(i)} ${i.title.replace(/^\S+\s*—\s*/, '— ')} \`${i.id}\``,
        )
      : ['- Nothing yet.']),
    '',
    '**Ready to start** (highest priority first, nothing they wait on is open)',
    '',
    ...(ready.length
      ? ready.map((t) => `- ${t.title} \`${t.id}\` (${t.priority})`)
      : [
          '- Nothing is ready; finish the in-progress work or its decisions first.',
        ]),
    '',
    `**Waiting on a decision:** ${blocked.length} tasks. Run \`pnpm roadmap list --status todo\` for the full list.`,
    '',
    `**Streams:** ${epics.length}. See [CHECKLIST.md](CHECKLIST.md) for every task and step.`,
    '',
    BLOCK_END,
  ]
  return (await format(md.join('\n'), { parser: 'markdown' })).trim()
}

export function withNextBlock(next: string, block: string): string {
  const start = next.indexOf(BLOCK_START)
  const end = next.indexOf(BLOCK_END)
  if (start < 0 || end < 0)
    throw new Error('NEXT.md is missing the tracker markers')
  return next.slice(0, start) + block + next.slice(end + BLOCK_END.length)
}

/** Box state per nod ID in a checklist (true = ticked). */
export function boxes(checklist: string): Map<string, boolean> {
  const result = new Map<string, boolean>()
  for (const m of checklist.matchAll(
    /^\s*- \[([ xX])\] .*`((?:task|subtask|bug)-\d+)`\s*$/gm,
  )) {
    result.set(m[2], m[1] !== ' ')
  }
  return result
}

/**
 * Status changes implied by the checklist: a box whose state differs from the
 * last sync was changed by hand and wins; everything else follows nod.
 */
export function checklistChanges(
  items: Item[],
  now: Map<string, boolean>,
  before: Record<string, boolean>,
): { id: string; status: Status }[] {
  const changes: { id: string; status: Status }[] = []
  for (const item of items) {
    const ticked = now.get(item.id)
    if (ticked === undefined || ticked === before[item.id]) continue
    if (ticked && item.status !== 'done' && item.status !== 'cancelled') {
      changes.push({ id: item.id, status: 'done' })
    } else if (!ticked && item.status === 'done') {
      changes.push({ id: item.id, status: 'todo' })
    }
  }
  return changes
}

function nod(...args: string[]): void {
  const result = spawnSync('nod', args, { cwd: ROADMAP_DIR, stdio: 'inherit' })
  if (result.error || result.status !== 0) {
    throw new Error(
      `nod ${args.join(' ')} failed. Is Bun installed (https://bun.sh)? Run commands through pnpm so node_modules/.bin is on PATH.`,
    )
  }
}

async function sync(): Promise<void> {
  let items = loadItems()
  const before = existsSync(STATE)
    ? (JSON.parse(readFileSync(STATE, 'utf8')) as Record<string, boolean>)
    : {}
  const changes = checklistChanges(
    items,
    boxes(readFileSync(CHECKLIST, 'utf8')),
    before,
  )
  for (const change of changes)
    nod('update', change.id, '--status', change.status)
  items = loadItems()
  // Close a task when its last open step was finished since the last sync.
  // A task reopened with nod while its steps stay done is left open.
  for (const task of items.filter(
    (i) => i.type === 'task' && i.status !== 'done',
  )) {
    const steps = counted(children(items, task.id, 'subtask'))
    const newlyDone = steps.some(
      (step) => step.status === 'done' && before[step.id] !== true,
    )
    if (steps.length > 0 && done(steps).length === steps.length && newlyDone) {
      nod('update', task.id, '--status', 'done')
      nod('note', task.id, 'All steps done; closed by roadmap sync.')
    }
  }
  items = loadItems()
  const checklist = await renderChecklist(items)
  writeFileSync(CHECKLIST, checklist)
  writeFileSync(
    STATE,
    JSON.stringify(Object.fromEntries(boxes(checklist)), null, 2) + '\n',
  )
  writeFileSync(
    NEXT,
    withNextBlock(readFileSync(NEXT, 'utf8'), await renderNextBlock(items)),
  )
}

/** Returns the names of generated files that are out of date. */
export async function staleFiles(): Promise<string[]> {
  const items = loadItems()
  const stale: string[] = []
  if (readFileSync(CHECKLIST, 'utf8') !== (await renderChecklist(items))) {
    stale.push('CHECKLIST.md')
  }
  const next = readFileSync(NEXT, 'utf8')
  if (next !== withNextBlock(next, await renderNextBlock(items)))
    stale.push('NEXT.md')
  return stale
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const command = process.argv[2]
  if (command === 'sync') {
    await sync()
  } else if (command === 'check') {
    const stale = await staleFiles()
    if (stale.length > 0) {
      console.error(`Out of date: ${stale.join(', ')}. Run pnpm roadmap:sync.`)
      process.exit(1)
    }
  } else {
    console.error('Usage: tracker.ts sync | check')
    process.exit(2)
  }
}
