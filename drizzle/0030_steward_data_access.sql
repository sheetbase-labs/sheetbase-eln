CREATE FUNCTION api.rotate_sql_login(p_workspace_id uuid, p_login_id uuid)
    RETURNS TABLE(id uuid, username text, password text, expires_at timestamp with time zone)
    LANGUAGE plpgsql SECURITY DEFINER
