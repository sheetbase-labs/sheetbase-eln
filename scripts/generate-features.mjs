/**
 * Collect the feature folders under `src/features/` into generated indexes.
 *
 * A feature registers its operations, events, API tables, assistant cards and
 * copy in files of its own folder, so two features built in parallel never
 * edit the same file. This script writes the lists that gather them:
 *
 *   src/features/index.gen.ts             every `<feature>/feature.ts`
 *   src/features/assistant.gen.ts         every `<feature>/assistant.ts`
 *   src/features/assistant.server.gen.ts  every `<feature>/assistant.server.ts`
 *   src/features/copy.gen.ts              every `<feature>/copy.ts`
 *
 * They are git-ignored, like the route tree: `pnpm generate`, typecheck, the
 * test layers, the dev server and the build all run this first. A file is only
 * rewritten when its contents change. Features are listed in folder-name
 * order, which is also the order their entries appear in each surface.
 *
 * Usage: node scripts/generate-features.mjs
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const DIR = `${ROOT}src/features`

const HEADER = `// Generated by scripts/generate-features.mjs. Do not edit, do not commit.\n`

/** The identifier a folder's exports are imported under: `lab-notes` → `labNotes`. */
const ident = (folder) =>
  folder.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())

function features() {
  if (!existsSync(DIR)) return []

  return readdirSync(DIR, { withFileTypes: true })
    .filter(
      (entry) => entry.isDirectory() && /^[a-z][a-z0-9-]*$/.test(entry.name),
    )
    .map((entry) => entry.name)
    .sort()
}

function write(path, contents) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null

  if (current !== contents) writeFileSync(path, contents)
}

/**
 * One index: `export const <name> = [a, b] as const` over every folder that
 * has `file`, each imported by its `exported` name.
 */
function index({ file, exported, name, type }) {
  const typeImport = type
    ? `import type { ${type.name} } from '${type.from}'\n`
    : ''

  const found = features().filter((folder) =>
    existsSync(`${DIR}/${folder}/${file}.ts`),
  )

  const imports = found
    .map(
      (folder) =>
        `import { ${exported} as ${ident(folder)} } from './${folder}/${file}'`,
    )
    .join('\n')

  const list = found.map(ident).join(', ')
  const check = type ? ` satisfies readonly ${type.name}[]` : ''

  return `${HEADER}${typeImport}${imports}${imports ? '\n\n' : ''}export const ${name} = [${list}] as const${check}\n`
}

export function generateFeatures() {
  write(
    `${DIR}/index.gen.ts`,
    index({
      file: 'feature',
      exported: 'feature',
      name: 'FEATURES',
      type: { name: 'Feature', from: './define' },
    }),
  )
  write(
    `${DIR}/assistant.gen.ts`,
    index({
      file: 'assistant',
      exported: 'assistant',
      name: 'FEATURE_ASSISTANTS',
    }),
  )
  write(
    `${DIR}/assistant.server.gen.ts`,
    index({
      file: 'assistant.server',
      exported: 'assistantServer',
      name: 'FEATURE_ASSISTANT_SERVERS',
      type: { name: 'FeatureAssistantServer', from: './define.server' },
    }),
  )

  const withCopy = features().filter((folder) =>
    existsSync(`${DIR}/${folder}/copy.ts`),
  )

  write(
    `${DIR}/copy.gen.ts`,
    `${HEADER}${withCopy
      .map(
        (folder) =>
          `import { copy as ${ident(folder)} } from './${folder}/copy'`,
      )
      .join(
        '\n',
      )}${withCopy.length ? '\n\n' : ''}/** Each feature's copy, read as \`t('features.<feature>.…')\`. */\nexport const featureCopy = {${withCopy
      .map((folder) => ` ${ident(folder)},`)
      .join('')}${withCopy.length ? ' ' : ''}}\n`,
  )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateFeatures()
}
