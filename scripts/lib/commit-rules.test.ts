import { describe, expect, it } from 'vitest'

import {
  checkCommit,
  checkPullRequest,
  stripAttribution,
} from './commit-rules.mjs'

const me = 'iamgp <170375+iamgp@users.noreply.github.com>'

describe('commit rules', () => {
  it('passes a clean conventional commit', () => {
    expect(
      checkCommit({
        message: 'feat(samples): add reservations\n\nBody.\n',
        author: me,
        committer: me,
      }),
    ).toEqual([])
  })

  it('refuses a plain-English subject', () => {
    expect(
      checkCommit({
        message: 'Move compound registration into the plugin',
        author: me,
      }),
    ).toHaveLength(1)
  })

  it('refuses assistant trailers, authors and merge commits', () => {
    const problems = checkCommit({
      message:
        'fix(x): y\n\nCo-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>\nClaude-Session: https://claude.ai/code/session_1\n',
      author: 'Claude <noreply@anthropic.com>',
      committer: me,
      parents: 2,
    })
    expect(problems).toHaveLength(4)
  })

  it('allows a human co-author', () => {
    expect(
      checkCommit({
        message: 'fix(x): y\n\nCo-Authored-By: Sam <sam@lab.org>\n',
        author: me,
      }),
    ).toEqual([])
  })

  it('strips attribution and the trailing gap it leaves', () => {
    expect(
      stripAttribution(
        'fix(x): y\n\nBody.\n\nCo-Authored-By: Claude Opus <noreply@anthropic.com>\nClaude-Session: https://claude.ai/code/session_1\n',
      ),
    ).toBe('fix(x): y\n\nBody.\n')
  })

  it('checks the PR title, body and branch', () => {
    expect(
      checkPullRequest({
        title: 'Bring planning up to the integration surface',
        body: '<!-- claude-projects-attribution: {} -->\n_Requested by **Gareth** · x_\n\nText\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_1)_',
        head: 'claude/project-thread-abc',
      }),
    ).toHaveLength(5)
    expect(
      checkPullRequest({
        title: 'feat(api): open people to the API',
        body: 'Text',
        head: 'feat/people',
      }),
    ).toEqual([])
  })
})
