#!/usr/bin/env python3
"""Generate the typed layer of the Python SDK from the public OpenAPI contract.

Reads ``docs/api/openapi/external-api-v0.json`` and writes
``src/sheetbase/_generated/``:

- ``models.py``: a ``TypedDict`` for every component schema and every RPC's
  parameters, so rows, inserts, patches and results are typed;
- ``tables.py``: one class per public table, offering only the HTTP methods the
  contract lists, collected on ``Tables`` / ``AsyncTables``;
- ``rpc.py``: one method per public RPC with keyword arguments (``p_`` prefix
  dropped), collected on ``Rpc`` / ``AsyncRpc``.

Run ``pnpm sdk:generate`` (or this script) after ``pnpm openapi:generate``.
``--check`` exits non-zero when the committed files are out of date; CI runs it.

Standard library only, so it runs anywhere Python 3.10+ does.
"""
from __future__ import annotations

import argparse
import json
import keyword
import re
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
SDK_ROOT = HERE.parent
REPO_ROOT = SDK_ROOT.parent.parent
DEFAULT_SPEC = REPO_ROOT / "docs" / "api" / "openapi" / "external-api-v0.json"
OUT_DIR = SDK_ROOT / "src" / "sheetbase" / "_generated"

HEADER = (
    "# Generated by sdks/python/scripts/generate.py from\n"
    "# docs/api/openapi/external-api-v0.json (contract {version}).\n"
    "# Do not edit by hand: run `pnpm sdk:generate`.\n"
)

# Names that would shadow something a method body or signature needs.
RESERVED_ARGS = {"self", "cls"}
SCALARS = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}


# ── naming ──────────────────────────────────────────────────────────────


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^0-9a-zA-Z]+", name) if part)


def ident(name: str) -> str:
    """A safe Python identifier for an argument or attribute."""
    cleaned = re.sub(r"\W", "_", name)
    if not cleaned or cleaned[0].isdigit():
        cleaned = f"_{cleaned}"
    if keyword.iskeyword(cleaned) or cleaned in RESERVED_ARGS:
        cleaned = f"{cleaned}_"
    return cleaned


def is_identifier(name: str) -> bool:
    return name.isidentifier() and not keyword.iskeyword(name)


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def py_literal(value: Any) -> str:
    """A Python literal for a JSON scalar (``true`` becomes ``True``)."""
    return repr(value) if isinstance(value, (bool, int, float)) or value is None else py_string(str(value))


def py_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def docstring(text: str, indent: str) -> str:
    text = (text or "").strip().replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if not text:
        return ""
    lines = text.splitlines()
    if len(lines) == 1:
        return f'{indent}"""{lines[0]}"""\n'
    body = "\n".join((f"{indent}{line}" if line.strip() else "") for line in lines)
    return f'{indent}"""\n{body}\n{indent}"""\n'


# ── schema → type annotation ────────────────────────────────────────────


class TypeMapper:
    def __init__(self, schemas: dict[str, Any]) -> None:
        self.schemas = schemas
        self.uses_literal = False
        self.extra_names: list[str] = []

    def annotate(self, schema: Any, *, depth: int = 0) -> str:
        if not isinstance(schema, dict) or depth > 6:
            return "Any"
        nullable = bool(schema.get("nullable"))
        inner = self._annotate(schema, depth)
        if nullable and inner not in ("Any", "None") and not inner.startswith("Optional["):
            return f"Optional[{inner}]"
        return inner

    def _annotate(self, schema: dict[str, Any], depth: int) -> str:
        if "$ref" in schema:
            name = ref_name(schema["$ref"])
            return py_string(name) if name in self.schemas else "Any"
        if "const" in schema:
            self.uses_literal = True
            return f"Literal[{py_literal(schema['const'])}]"
        if "enum" in schema:
            values = [v for v in schema["enum"] if v is not None]
            if values and all(isinstance(v, (str, int, bool)) for v in values):
                self.uses_literal = True
                literal = f"Literal[{', '.join(py_literal(v) for v in values)}]"
                return f"Optional[{literal}]" if None in schema["enum"] else literal
        for key in ("oneOf", "anyOf"):
            if key in schema:
                return self._union([self.annotate(s, depth=depth + 1) for s in schema[key]])
        if "allOf" in schema:
            parts = schema["allOf"]
            return self.annotate(parts[0], depth=depth + 1) if len(parts) == 1 else "Dict[str, Any]"
        kind = schema.get("type")
        if isinstance(kind, list):
            return self._union([self._annotate({**schema, "type": k}, depth) for k in kind])
        if kind in SCALARS:
            return SCALARS[kind]
        if kind == "array":
            return f"List[{self.annotate(schema.get('items'), depth=depth + 1)}]"
        if kind == "object" or "properties" in schema:
            extra = schema.get("additionalProperties")
            if not schema.get("properties") and isinstance(extra, dict) and extra:
                return f"Dict[str, {self.annotate(extra, depth=depth + 1)}]"
            return "Dict[str, Any]"
        return "Any"

    @staticmethod
    def _union(parts: list[str]) -> str:
        seen: list[str] = []
        for part in parts:
            if part not in seen:
                seen.append(part)
        if "Any" in seen:
            return "Any"
        has_none = "None" in seen
        rest = [p for p in seen if p != "None"]
        if not rest:
            return "None"
        core = rest[0] if len(rest) == 1 else f"Union[{', '.join(rest)}]"
        return f"Optional[{core}]" if has_none else core


# ── models.py ───────────────────────────────────────────────────────────


def typed_dict(name: str, schema: dict[str, Any], mapper: TypeMapper) -> str:
    properties: dict[str, Any] = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    description = schema.get("description", "")
    variants = schema.get("oneOf") or schema.get("anyOf")
    if not properties and variants and all(
        isinstance(v, dict) and v.get("properties") for v in variants
    ):
        return union_of_variants(name, schema, variants, mapper)
    if not properties:
        alias = mapper.annotate(schema)
        if alias == "Dict[str, Any]" or alias.startswith("Dict["):
            return f"{name} = {alias}\n"
        if alias.startswith('"'):
            alias = alias.strip('"')
        return f"{name} = {alias}\n"

    fields = [(key, mapper.annotate(value), key in required) for key, value in properties.items()]
    if not all(is_identifier(key) for key in properties):
        items = ", ".join(f"{py_string(k)}: {t}" for k, t, _ in fields)
        return f"{name} = TypedDict({py_string(name)}, {{{items}}}, total=False)\n"

    out: list[str] = []
    req = [f for f in fields if f[2]]
    opt = [f for f in fields if not f[2]]
    doc = docstring(description, "    ")
    if req and opt:
        out.append(f"class _{name}Required(TypedDict):\n")
        out.extend(f"    {k}: {t}\n" for k, t, _ in req)
        out.append(f"\n\nclass {name}(_{name}Required, total=False):\n")
        out.append(doc)
        out.extend(f"    {k}: {t}\n" for k, t, _ in opt)
    else:
        total = "" if req else ", total=False"
        out.append(f"class {name}(TypedDict{total}):\n")
        out.append(doc)
        out.extend(f"    {k}: {t}\n" for k, t, _ in fields)
    return "".join(out)


def variant_name(name: str, index: int, variant: dict[str, Any], taken: set[str]) -> str:
    for value in (variant.get("properties") or {}).values():
        if isinstance(value, dict) and isinstance(value.get("const"), str):
            candidate = f"{name}{pascal(value['const'])}"
            break
        if isinstance(value, dict) and isinstance(value.get("enum"), list) and len(value["enum"]) == 1:
            candidate = f"{name}{pascal(str(value['enum'][0]))}"
            break
    else:
        candidate = f"{name}Variant{index + 1}"
    while candidate in taken:
        candidate = f"{candidate}_"
    taken.add(candidate)
    return candidate


def union_of_variants(
    name: str, schema: dict[str, Any], variants: list[dict[str, Any]], mapper: TypeMapper
) -> str:
    taken: set[str] = set(mapper.schemas)
    parts: list[str] = []
    names: list[str] = []
    for index, variant in enumerate(variants):
        sub = variant_name(name, index, variant, taken)
        names.append(sub)
        mapper.extra_names.append(sub)
        parts.append(typed_dict(sub, variant, mapper))
    doc = (schema.get("description") or "").strip()
    comment = "".join(f"# {line}\n" for line in doc.splitlines()) if doc else ""
    alias = f"{comment}{name} = Union[{', '.join(py_string(n) for n in names)}]\n"
    return "\n\n".join(parts) + "\n\n" + alias


# ── operations ──────────────────────────────────────────────────────────


def json_body_schema(operation: dict[str, Any]) -> dict[str, Any]:
    content = (operation.get("requestBody") or {}).get("content") or {}
    return (content.get("application/json") or {}).get("schema") or {}


def success_schema(operation: dict[str, Any]) -> Any:
    responses = operation.get("responses") or {}
    for code in ("200", "201"):
        content = (responses.get(code) or {}).get("content") or {}
        schema = (content.get("application/json") or {}).get("schema")
        if schema is not None:
            return schema
    return None


def array_item_ref(schema: Any) -> str | None:
    if isinstance(schema, dict) and schema.get("type") == "array":
        items = schema.get("items") or {}
        if "$ref" in items:
            return ref_name(items["$ref"])
    return None


def collect(spec: dict[str, Any]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    tables: list[dict[str, Any]] = []
    rpcs: list[dict[str, Any]] = []
    for path, item in spec["paths"].items():
        if path.startswith("/api/db/rpc/"):
            operation = item.get("post")
            if operation:
                rpcs.append({"name": path.rsplit("/", 1)[-1], "op": operation})
        elif path.startswith("/api/db/"):
            name = path[len("/api/db/"):]
            methods = {m: op for m, op in item.items() if m in ("get", "head", "post", "patch", "delete")}
            row = None
            if "get" in methods:
                row = array_item_ref(success_schema(methods["get"]))
            insert = patch = None
            if "post" in methods:
                body = json_body_schema(methods["post"])
                insert = ref_name(body["$ref"]) if "$ref" in body else None
            if "patch" in methods:
                body = json_body_schema(methods["patch"])
                patch = ref_name(body["$ref"]) if "$ref" in body else None
            tables.append(
                {"name": name, "methods": methods, "row": row, "insert": insert, "patch": patch}
            )
    tables.sort(key=lambda t: t["name"])
    rpcs.sort(key=lambda r: r["name"])
    return tables, rpcs


def render_models(spec: dict[str, Any], rpcs: list[dict[str, Any]], mapper: TypeMapper) -> str:
    schemas = spec["components"]["schemas"]
    blocks: list[str] = []
    for name in sorted(schemas):
        blocks.append(typed_dict(name, schemas[name], mapper))
    for rpc in rpcs:
        body = json_body_schema(rpc["op"])
        params_name = f"{pascal(rpc['name'])}Params"
        if body.get("properties"):
            blocks.append(typed_dict(params_name, body, mapper))
        else:
            blocks.append(f"{params_name} = Dict[str, Any]\n")
    names = sorted(
        [*schemas, *mapper.extra_names, *(f"{pascal(r['name'])}Params" for r in rpcs)]
    )
    typing_names = ["Any", "Dict", "List", "Optional", "TypedDict", "Union"]
    if mapper.uses_literal:
        typing_names.insert(3, "Literal")
    head = (
        HEADER.format(version=spec["info"]["version"])
        + '"""Typed shapes for every schema in the public API contract."""\n'
        + "from __future__ import annotations\n\n"
        + f"from typing import {', '.join(typing_names)}\n\n"
        + "__all__ = [\n"
        + "".join(f"    {py_string(n)},\n" for n in names)
        + "]\n\n\n"
    )
    return head + "\n\n".join(blocks)


def scopes_line(operation: dict[str, Any]) -> str:
    scopes = operation.get("x-sheetbase-scopes") or []
    return f"Scopes: {', '.join(scopes)}." if scopes else ""


def render_tables(spec: dict[str, Any], tables: list[dict[str, Any]]) -> str:
    used: set[str] = set()
    classes: list[str] = []
    for table in tables:
        methods = table["methods"]
        row = table["row"] or "Dict[str, Any]"
        for model in (table["row"], table["insert"], table["patch"]):
            if model:
                used.add(model)
        cls = f"{pascal(table['name'])}Table"
        for prefix, async_ in (("", False), ("Async", True)):
            bases: list[str] = []
            if "get" in methods or "head" in methods:
                bases.append(f"{prefix}ReadableTable[{row}]")
            if "post" in methods:
                bases.append(f"{prefix}InsertableTable[{row}, {table['insert'] or 'Dict[str, Any]'}]")
            if "patch" in methods:
                bases.append(f"{prefix}UpdatableTable[{row}, {table['patch'] or 'Dict[str, Any]'}]")
            if "delete" in methods:
                bases.append(f"{prefix}DeletableTable[{row}]")
            if not bases:
                bases.append(f"{prefix}Table[{row}]")
            verbs = ", ".join(m.upper() for m in methods)
            summary = f"``/api/db/{table['name']}`` ({verbs})."
            scopes = sorted({s for op in methods.values() for s in op.get("x-sheetbase-scopes") or []})
            doc = summary + (f"\n\nScopes: {', '.join(scopes)}." if scopes else "")
            joined = ", ".join(bases)
            if len(joined) + len(cls) > 80:
                joined = "\n" + "".join(f"    {b},\n" for b in bases)
            classes.append(
                f"class {prefix}{cls}({joined}):\n"
                + docstring(doc, "    ")
                + f"    name = {py_string(table['name'])}\n"
            )

    def collection(prefix: str) -> str:
        transport = "AsyncHttpTransport" if prefix else "HttpTransport"
        attrs = "".join(
            f"        self.{ident(t['name'])} = {prefix}{pascal(t['name'])}Table(transport)\n"
            for t in tables
        )
        names = "".join(f"        {py_string(t['name'])},\n" for t in tables)
        return (
            f"class {prefix}Tables:\n"
            f'    """Every public table, e.g. ``client.tables.projects.list()``."""\n\n'
            f"    NAMES = (\n{names}    )\n\n"
            f"    def __init__(self, transport: {transport}) -> None:\n"
            f"{attrs}\n"
            f"    def __getitem__(self, name: str) -> {prefix}Table[Any]:\n"
            f"        if name not in self.NAMES:\n"
            f"            raise KeyError(f\"{{name}} is not a public table\")\n"
            f"        return getattr(self, name)  # type: ignore[no-any-return]\n\n"
            f"    def __iter__(self) -> Iterator[str]:\n"
            f"        return iter(self.NAMES)\n"
        )

    base_names = sorted(
        {
            f"{p}{b}"
            for p in ("", "Async")
            for b in ("Table", "ReadableTable", "InsertableTable", "UpdatableTable", "DeletableTable")
        }
    )
    body_text = "\n\n".join(classes) + collection("") + collection("Async")
    base_names = [n for n in base_names if re.search(rf"\b{n}\b", body_text)]
    dict_import = ", Dict" if "Dict[" in body_text else ""
    head = (
        HEADER.format(version=spec["info"]["version"])
        + '"""One class per public table, offering only the methods the contract allows."""\n'
        + "from __future__ import annotations\n\n"
        + "from collections.abc import Iterator\n"
        + f"from typing import Any{dict_import}\n\n"
        + "from sheetbase._http import AsyncHttpTransport, HttpTransport\n"
        + "from sheetbase._tables import (\n"
        + "".join(f"    {n},\n" for n in base_names)
        + ")\n"
        + (
            "from sheetbase._generated.models import (\n"
            + "".join(f"    {n},\n" for n in sorted(used))
            + ")\n"
            if used
            else ""
        )
        + "\n\n"
    )
    return head + "\n\n".join(classes) + "\n\n" + collection("") + "\n\n" + collection("Async")


def render_rpc(spec: dict[str, Any], rpcs: list[dict[str, Any]], mapper: TypeMapper) -> str:
    schemas = spec["components"]["schemas"]
    methods_sync: list[str] = []
    methods_async: list[str] = []
    used: set[str] = set()

    for rpc in rpcs:
        op = rpc["op"]
        body = json_body_schema(op)
        props: dict[str, Any] = body.get("properties") or {}
        required = set(body.get("required") or [])
        args: list[str] = []
        mapping: list[tuple[str, str, bool]] = []
        taken: set[str] = set()
        ordered = [k for k in props if k in required] + [k for k in props if k not in required]
        for wire in ordered:
            name = ident(wire[2:] if wire.startswith("p_") and len(wire) > 2 else wire)
            while name in taken:
                name = f"{name}_"
            taken.add(name)
            annotation = mapper.annotate(props[wire])
            for ref in re.findall(r'"(\w+)"', annotation):
                if ref in schemas:
                    used.add(ref)
            if wire in required:
                args.append(f"{name}: {annotation}")
            else:
                args.append(f"{name}: Union[{annotation}, Unset] = UNSET")
            mapping.append((name, wire, wire in required))

        result = mapper.annotate(success_schema(op)) if success_schema(op) is not None else "Any"
        for ref in re.findall(r'"(\w+)"', result):
            if ref in schemas:
                used.add(ref)

        params_list = ["self", *(["*"] + args if args else [])]
        signature = ", ".join(params_list)
        if len(signature) + len(rpc["name"]) + len(result) > 80:
            signature = "\n" + "".join(f"        {p},\n" for p in params_list) + "    "
        doc_parts = [op.get("summary", ""), op.get("description", ""), scopes_line(op)]
        doc_parts.append(f"``POST /api/db/rpc/{rpc['name']}``")
        doc = "\n\n".join(p.strip() for p in doc_parts if p and p.strip())
        build = "        _request_body: Dict[str, Any] = {}\n"
        for name, wire, is_required in mapping:
            if is_required:
                build += f"        _request_body[{py_string(wire)}] = {name}\n"
            else:
                build += f"        if not isinstance({name}, Unset):\n"
                build += f"            _request_body[{py_string(wire)}] = {name}\n"
        method = ident(rpc["name"])
        methods_sync.append(
            f"    def {method}({signature}) -> {result}:\n"
            + docstring(doc, "        ")
            + build
            + f"        return self._call({py_string(rpc['name'])}, _request_body)  # type: ignore[no-any-return]\n"
        )
        methods_async.append(
            f"    async def {method}({signature}) -> {result}:\n"
            + docstring(doc, "        ")
            + build
            + f"        return await self._call({py_string(rpc['name'])}, _request_body)  # type: ignore[no-any-return]\n"
        )

    names = "".join(f"        {py_string(r['name'])},\n" for r in rpcs)
    common = (
        "    NAMES = (\n" + names + "    )\n\n"
    )
    sync_cls = (
        "class Rpc:\n"
        '    """Every public RPC as a typed method, e.g. ``client.rpc.create_project(title=...)``.\n\n'
        "    Calling the object directly stays supported for raw access:\n"
        '    ``client.rpc("create_project", title="...")`` adds the ``p_`` prefix for you.\n'
        '    """\n\n'
        + common
        + "    def __init__(self, transport: HttpTransport) -> None:\n"
        "        self._transport = transport\n\n"
        "    def __call__(self, name: str, **params: Any) -> Any:\n"
        "        return self._call(name, _prefixed(params))\n\n"
        "    def _call(self, name: str, body: Dict[str, Any]) -> Any:\n"
        '        return self._transport.post(f"/api/db/rpc/{name}", json_body=body)\n\n'
        + "\n".join(methods_sync)
    )
    async_cls = (
        "class AsyncRpc:\n"
        '    """Async counterpart of :class:`Rpc`."""\n\n'
        + common
        + "    def __init__(self, transport: AsyncHttpTransport) -> None:\n"
        "        self._transport = transport\n\n"
        "    async def __call__(self, name: str, **params: Any) -> Any:\n"
        "        return await self._call(name, _prefixed(params))\n\n"
        "    async def _call(self, name: str, body: Dict[str, Any]) -> Any:\n"
        '        return await self._transport.post(f"/api/db/rpc/{name}", json_body=body)\n\n'
        + "\n".join(methods_async)
    )
    rpc_text = sync_cls + async_cls
    typing_names = [
        n for n in ("Any", "Dict", "List", "Literal", "Optional", "Union")
        if re.search(rf"\b{n}\[", rpc_text) or (n == "Any" and "Any" in rpc_text)
    ]
    head = (
        HEADER.format(version=spec["info"]["version"])
        + '"""One typed method per public RPC."""\n'
        + "from __future__ import annotations\n\n"
        + f"from typing import {', '.join(typing_names)}\n\n"
        + "from sheetbase._http import AsyncHttpTransport, HttpTransport\n"
        + "from sheetbase._unset import UNSET, Unset\n"
        + (
            "from sheetbase._generated.models import (\n"
            + "".join(f"    {n},\n" for n in sorted(used))
            + ")\n"
            if used
            else ""
        )
        + "\n\n"
        + "def _prefixed(params: Dict[str, Any]) -> Dict[str, Any]:\n"
        + '    return {k if k.startswith("p_") else f"p_{k}": v for k, v in params.items()}\n\n\n'
    )
    return head + sync_cls + "\n\n" + async_cls


def render_init(spec: dict[str, Any]) -> str:
    return (
        HEADER.format(version=spec["info"]["version"])
        + '"""The generated, typed layer of the SDK. See ``scripts/generate.py``."""\n'
        + "from sheetbase._generated.rpc import AsyncRpc, Rpc\n"
        + "from sheetbase._generated.tables import AsyncTables, Tables\n\n"
        + f"CONTRACT_VERSION = {py_string(spec['info']['version'])}\n\n"
        + '__all__ = ["AsyncRpc", "AsyncTables", "CONTRACT_VERSION", "Rpc", "Tables"]\n'
    )


def render(spec: dict[str, Any]) -> dict[str, str]:
    tables, rpcs = collect(spec)
    mapper = TypeMapper(spec["components"]["schemas"])
    files = {
        "models.py": render_models(spec, rpcs, mapper),
        "tables.py": render_tables(spec, tables),
        "rpc.py": render_rpc(spec, rpcs, mapper),
        "__init__.py": render_init(spec),
    }
    return {name: text.rstrip() + "\n" for name, text in files.items()}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    parser.add_argument("--out", type=Path, default=OUT_DIR)
    parser.add_argument("--check", action="store_true", help="fail if the committed files differ")
    args = parser.parse_args(argv)

    spec = json.loads(args.spec.read_text(encoding="utf-8"))
    files = render(spec)
    if args.check:
        stale = [
            name
            for name, text in files.items()
            if not (args.out / name).exists() or (args.out / name).read_text(encoding="utf-8") != text
        ]
        extra = sorted(
            p.name for p in args.out.glob("*.py") if p.name not in files
        ) if args.out.exists() else []
        if stale or extra:
            print(
                "The Python SDK is out of date with the OpenAPI contract "
                f"({', '.join(stale + extra)}). Run `pnpm sdk:generate` and commit the result.",
                file=sys.stderr,
            )
            return 1
        print("Python SDK matches the OpenAPI contract.")
        return 0

    args.out.mkdir(parents=True, exist_ok=True)
