/**
 * A plugin operation, declared once in the manifest, becomes an
 * `OperationDescriptor` (the shape `src/lib/operations` generates every
 * integration surface from):
 *
 * - the pipeline action (`pipelineActionsFrom`), named `plugin.<key>.<id>`;
 * - the assistant tool, a confirm card for a `write` and an answer for a
 *   `read` (`assistantToolsFrom`, `operationPresentation`);
 * - the agent and MCP tool, through the same name and the agent action policy;
 * - the API route, `POST /api/plugins/<key>/<id>` (see `api-route.server.ts`).
 *
 * Webhook events are generic: every call is written to the change log as
 * `extension.invoked`, with the plugin, operation and outcome in the payload.
 *
 * Pure and browser safe. What the plugin does is Python in its package; what
 * the surfaces say about it is generated here, so they cannot drift.
 */
import type {
  OperationDescriptor,
  OperationInput,
  OperationInputType,
} from '../operations/descriptor'
import { callableItems } from './callables'
import type { ExtensionManifest } from './manifest'
import { pluginOperationName } from './points'
import type { ExtensionField, ExtensionFieldType } from './points'

const INPUT_TYPES: Record<ExtensionFieldType, OperationInputType> = {
  text: 'text',
  number: 'num',
  integer: 'int',
  boolean: 'bool',
  date: 'date',
  json: 'json',
}

export const fieldToInput = (field: ExtensionField): OperationInput => {
  const input: OperationInput = {
    name: field.name,
    type: INPUT_TYPES[field.type],
    required: field.required,
    nullable: !field.required,
  }

  if (field.description) input.description = field.description

  return input
}

/** The descriptors for the operations one plugin install declares. */
export function pluginOperationDescriptors(
  key: string,
  manifest: ExtensionManifest,
  options: { pluginName?: string } = {},
): OperationDescriptor[] {
  const source = `plugin:${key}`
  const pluginName = options.pluginName ?? manifest.name

  return callableItems(manifest).map(({ declaration: operation }) => {
    const name = pluginOperationName(key, operation.id)

    return {
      name,
      label: operation.title,
      description: `${operation.description} (from the ${pluginName} plugin.)`,
      kind: operation.access,
      scope: operation.access === 'read' ? 'lab:read' : 'lab:write',
      inputs: operation.inputs.map(fieldToInput),
      result: 'json',
      // The API route is generated by the plugin runtime, not by `LAB_RPCS`.
      api: 'elsewhere',
      assistant: {
        tool: name,
        presentation: operation.access === 'read' ? 'answer' : 'card',
        vocabulary: operation.access === 'read' ? 'read' : 'propose',
      },
      pipeline: { label: operation.title },
      source,
    } satisfies OperationDescriptor
  })
}
