export interface ServiceCredentialOpenApi {
  openapi: '3.1.0'
  info: {
    title: string
    version: string
    description: string
  }
  servers: Array<{ url: string; description: string }>
  tags: Array<{ name: string; description: string }>
  paths: Record<string, OpenApiPathItem>
  components: {
    securitySchemes: Record<string, unknown>
    schemas: Record<string, JsonSchema>
    parameters: Record<string, unknown>
  }
}

function tokenErrorSchema(): JsonSchema {
  return {
    type: 'object',
    required: ['error'],
    additionalProperties: false,
    properties: {
      error: {
        type: 'object',
        required: ['code', 'message'],
        additionalProperties: false,
        properties: {
          code: { type: 'string', enum: [...TOKEN_ERROR_CODES] },
          message: { type: 'string' },
        },
      },
    },
  }
}

function proxyErrorSchema(): JsonSchema {
  return {
    type: 'object',
    required: ['error'],
    additionalProperties: false,
    properties: {
      error: {
        type: 'object',
        required: ['category', 'message'],
        additionalProperties: false,
        properties: {
          category: { type: 'string', enum: [...ERROR_CATEGORIES] },
          message: { type: 'string' },
          request_id: {
            type: 'string',
            description:
              'Correlation id from `x-request-id` or generated by the proxy.',
          },
        },
      },
    },
  }
}

function tokenErrorResponses(): Record<string, unknown> {
  return {
    '400': {
      description:
        '`invalid_request` or `invalid_scope`. Envelope uses `error.code`.',
      content: {
        'application/json': {
          schema: { $ref: '#/components/schemas/TokenError' },
        },
      },
    },
    '401': {
      description: '`invalid_credential`.',
      content: {
        'application/json': {
          schema: { $ref: '#/components/schemas/TokenError' },
        },
      },
    },
    '403': {
      description: '`revoked`, `expired`, or `insufficient_scope`.',
      content: {
        'application/json': {
          schema: { $ref: '#/components/schemas/TokenError' },
        },
      },
    },
    '429': {
      description:
        '`rate_limited` — 5 failed exchanges per prefix / 15 minutes.',
      content: {
        'application/json': {
          schema: { $ref: '#/components/schemas/TokenError' },
        },
      },
    },
    '500': {
      description: '`server_error`.',
      content: {
        'application/json': {
          schema: { $ref: '#/components/schemas/TokenError' },
        },
      },
    },
  }
}

function proxyErrorResponses(): Record<string, unknown> {
  const content = {
    'application/json': {
      schema: { $ref: '#/components/schemas/ProxyError' },
    },
  }
  return {
    '400': { description: '`validation_error`', content },
    '401': { description: '`unauthenticated`', content },
    '403': {
      description:
        '`permission_denied` — missing scope, revoked credential, or RLS',
      content,
    },
    '404': { description: '`not_found` or hidden by RLS', content },
    '409': { description: '`stale_version` or `conflict`', content },
    '422': {
      description:
        '`missing_link`, `invalid_transition`, `invalid_properties`, or `template_not_instantiable`',
      content,
    },
    '502': { description: '`service_unavailable`', content },
  }
}

function scopeExtension(scopes: readonly Scope[]): Record<string, unknown> {
  return {
    'x-sheetbase-scopes': [...scopes],
  }
}

function tagForTable(resource: string): string {
  if (
    resource.startsWith('dataset_schema') ||
    resource.startsWith('sheet_definition')
  ) {
    return 'Catalogues'
  }
  if (resource.startsWith('notebook_template')) return 'Templates'
  if (resource.startsWith('dataset')) return 'Datasets'
  if (resource.startsWith('sheet_')) return 'Sheets'
  return 'Projects'
}

function tagForRpc(resource: string, scopes: readonly Scope[]): string {
  if (resource.startsWith('query_dataset') || resource.includes('dataset')) {
    return 'Datasets'
  }
  if (
    resource.includes('sheet_instance') ||
    resource.includes('sheet_record')
  ) {
    return 'Sheets'
  }
  if (resource.includes('notebook_template')) return 'Templates'
  if (resource === 'preview_submission_digest') return 'Reviews'
  if (scopes.includes('models:read') || scopes.includes('models:write')) {
    return 'Models'
  }
  if (resource === 'search') return 'Search'
  return 'Projects'
}

