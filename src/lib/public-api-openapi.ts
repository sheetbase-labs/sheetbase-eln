function tableReadResponses(resource: string): Record<string, unknown> {
  return {
    '200': {
      description: `JSON array of \`${resource}\` rows. With \`Prefer: count=exact\`, \`Content-Range\` is \`start-end/total\` (e.g. \`0-24/123\`).`,
      headers: {
        'Content-Range': {
          description:
            'Present when Prefer: count=* is honoured. Total is the number after the slash.',
          schema: { type: 'string', examples: ['0-24/123', '0-0/42'] },
        },
        'x-request-id': {
          schema: { type: 'string' },
          description: 'Proxy correlation id.',
        },
      },
      content: {
        'application/json': {
          schema: { type: 'array', items: { type: 'object' } },
        },
      },
    },
    '206': {
      description: 'Partial content when a `Range` header is used.',
      headers: {
        'Content-Range': { schema: { type: 'string' } },
      },
    },
    ...proxyErrorResponses(),
  }
}

function tableOperations(resource: string): OpenApiPathItem {
  const access = EXTERNAL_TABLE_ACCESS[resource]
  const item: OpenApiPathItem = {}
  const readOp: OpenApiOperation = {
    tags: [tagForTable(resource)],
    summary: `Read ${resource}`,
    operationId: `get_${resource}`,
    security: [{ bearerAuth: [] }],
    ...scopeExtension([access.read]),
    description: [
      `GET \`${resource}\` through PostgREST.`,
      'Pagination: `limit` and `offset` query parameters.',
      'Sort: `order=column.asc` or `column.desc`; repeat `order` for multiple columns.',
      `Filters: \`{column}={operator}.{value}\` where operator is one of \`${POSTGREST_FILTER_OPERATORS.join(', ')}\`. Examples: \`id=eq.<uuid>\`, \`kind=eq.experiment\`, \`status=in.(draft,in-progress)\`.`,
      'Logic: `and=(status.eq.draft,kind.eq.experiment)` and `or=(...)`.',
      'Count: send header `Prefer: count=exact` (optionally with `Range: 0-0` or `limit=0`) and read the total from `Content-Range`.',
      'Column selection: `select=id,title`.',
    ].join('\n\n'),
    parameters: TABLE_QUERY_PARAMETERS,
    responses: tableReadResponses(resource),
  }
  item.get = readOp
  item.head = {
    ...readOp,
    operationId: `head_${resource}`,
    summary: `Headers for ${resource}`,
    description:
      'Same query string and `Prefer` / `Range` headers as GET. Use with `Prefer: count=exact` to obtain `Content-Range` without a body.',
  }

  if (!access.write) return item

  const projectWritable = [
    'projects',
    'folders',
    'records',
    'blocks',
    'record_links',
    'record_field_definitions',
  ]
  if (resource === 'datasets') {
    item.post = {
      tags: ['Datasets'],
      summary: 'Create a Dataset (INSERT)',
      operationId: 'post_datasets',
      security: [{ bearerAuth: [] }],
      ...scopeExtension(['datasets:write']),
      description:
        'There is no `create_dataset` RPC. INSERT `workspace_id` (must match the JWT), `schema_version_id` (published Schema Version), and `name`. Row writes use `commit_dataset_row_batch`, not PATCH.',
      requestBody: {
        required: true,
        content: {
          'application/json': {
            schema: {
              type: 'object',
              additionalProperties: false,
              required: ['workspace_id', 'schema_version_id', 'name'],
              properties: {
                workspace_id: { type: 'string', format: 'uuid' },
                schema_version_id: { type: 'string', format: 'uuid' },
                name: { type: 'string' },
                description: { type: 'string', nullable: true },
                primary_project_id: {
                  type: 'string',
                  format: 'uuid',
                  nullable: true,
                },
              },
            },
          },
        },
      },
      responses: {
        '201': {
          description:
            'Created Dataset row (array or object depending on Prefer).',
        },
        ...proxyErrorResponses(),
      },
    }
    return item
  }
  if (!projectWritable.includes(resource)) return item

  item.post = {
    tags: ['Projects'],
    summary: `Create ${resource}`,
    operationId: `post_${resource}`,
    security: [{ bearerAuth: [] }],
    ...scopeExtension([access.write]),
    description: `PostgREST INSERT. Prefer domain RPCs when one exists (records, blocks, links). Filter mutations with \`id=eq.<uuid>\`.`,
    requestBody: {
      required: true,
      content: {
        'application/json': {
          schema: {
            type: 'object',
            description: `Columns of \`${resource}\`.`,
          },
        },
      },
    },
    responses: {
      '201': { description: `Created ${resource}` },
      ...proxyErrorResponses(),
    },
  }
  item.patch = {
    tags: ['Projects'],
    summary: `Update ${resource}`,
    operationId: `patch_${resource}`,
    security: [{ bearerAuth: [] }],
    ...scopeExtension([access.write]),
    description:
      'PostgREST PATCH. Always include a row filter (`id=eq.<uuid>`). Unfiltered PATCH is rejected by PostgREST in this deployment when Prefer handling=strict is used for scientific tables; still send an explicit filter.',
    parameters: [
      { $ref: '#/components/parameters/ColumnFilter' },
      { $ref: '#/components/parameters/Prefer' },
    ],
    requestBody: {
      required: true,
      content: {
        'application/json': {
          schema: {
            type: 'object',
            description: `Columns of \`${resource}\`.`,
          },
        },
      },
    },
    responses: {
      '200': { description: `Updated ${resource}` },
      ...proxyErrorResponses(),
    },
  }
  return item
}

function rpcOperation(resource: string, scopes: Scope[]): OpenApiOperation {
  const contract = RPC_CONTRACTS[resource]
  return {
    tags: [tagForRpc(resource, scopes)],
    summary: contract.summary,
    operationId: `rpc_${resource}`,
    security: [{ bearerAuth: [] }],
    ...scopeExtension(scopes),
    description: contract.description,
    requestBody: {
      required: true,
      content: {
        'application/json': {
          schema: {
            type: 'object',
            additionalProperties: false,
            required: contract.required,
            properties: contract.properties,
          },
        },
      },
    },
    responses: {
      '200': {
        description: `Result of ${resource}`,
        content: {
          'application/json': { schema: contract.result },
        },
      },
      ...proxyErrorResponses(),
    },
  }
}

