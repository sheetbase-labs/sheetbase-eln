function row(
  table: string,
  extra: string,
  properties: Record<string, JsonSchema>,
  required: string[],
): JsonSchema {
  return {
    type: 'object',
    additionalProperties: false,
    description: `\`api.${table}\` row (snake_case). ${extra}`,
    required,
    properties,
  }
}

